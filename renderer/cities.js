function stripAccents(value) {
  return value.normalize("NFD").replace(/\p{M}/gu, "");
}

function normalizeKey(value) {
  return stripAccents(String(value || ""))
    .toLowerCase()
    .trim()
    .replace(/ß/g, "ss")
    .replace(/[''`´]/g, "")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

export function isoForCity(cityId, cityName) {
  const id = String(cityId || "").toLowerCase().trim();
  const name = String(cityName || "").toLowerCase().trim();
  const idToken = normalizeKey(id);
  const nameToken = normalizeKey(name);

  return (
    CITY_COUNTRY[id] ||
    CITY_COUNTRY[idToken] ||
    NAME_COUNTRY[name] ||
    NAME_COUNTRY[stripAccents(name)] ||
    CITY_COUNTRY[nameToken] ||
    NAME_COUNTRY[nameToken.replace(/_/g, " ")] ||
    ""
  );
}

export function flagImageUrl(iso) {
  if (!iso || iso.length !== 2) return "";
  // Kosovo uses XK in many flag CDNs
  return `https://flagcdn.com/24x18/${iso.toLowerCase()}.png`;
}
